import { z } from 'zod';

export const MemoryItemSchema = z.object({
  id: z.string(),
  image: z.string(),
  title: z.string(),
  description: z.string(),
  date: z.string(),
  tag: z.string().optional(),
});

export const TimelineItemSchema = z.object({
  id: z.string(),
  date: z.string(),
  title: z.string(),
  description: z.string(),
  tag: z.string().optional(),
  image: z.string().optional(),
  icon: z.string().optional(),
});

export const BirthdayConfigSchema = z.object({
  recipientName: z.string(),
  recipientNickname: z.string().optional(),
  senderName: z.string(),
  birthdayDate: z.string(),
  age: z.number().optional(),
  theme: z.enum(['galaxy', 'nebula', 'aurora', 'supernova']).default('galaxy'),

  hero: z.object({
    badge: z.string(),
    preTitle: z.string(),
    title: z.string(),
    subtitle: z.string(),
    ctaText: z.string(),
  }),

  cake: z.object({
    heading: z.string(),
    subtitle: z.string(),
    candleWish: z.string(),
    blowButtonText: z.string(),
    relightButtonText: z.string(),
    afterBlowMessage: z.string(),
  }),

  memories: z.array(MemoryItemSchema),

  timeline: z.array(TimelineItemSchema),

  gift: z.object({
    title: z.string(),
    subtitle: z.string(),
    closedHint: z.string(),
    openTitle: z.string(),
    badge: z.string(),
    message: z.string(),
    rewardTitle: z.string(),
    rewardDetails: z.array(z.string()),
    ps: z.string(),
  }),

  letter: z.object({
    title: z.string(),
    subtitle: z.string(),
    salutation: z.string(),
    paragraphs: z.array(z.string()),
    signature: z.string(),
    footerNote: z.string(),
  }),

  finale: z.object({
    quote: z.string(),
    heading: z.string(),
    subheading: z.string(),
    replayButtonText: z.string(),
  }),

  music: z.object({
    enabled: z.boolean(),
    trackName: z.string(),
    artist: z.string(),
    source: z.string(), // mp3 path or synthesized fallback
    autoPlayPrompt: z.string(),
  }),
});

